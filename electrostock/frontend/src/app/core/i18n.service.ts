export type TranslationKey = keyof typeof translations['es-CO'];

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly locale = signal<'es-CO' | 'en'>(localStorage.getItem('electrostock.locale') === 'en' ? 'en' : 'es-CO');

  translate(key: TranslationKey): string {
    return translations[this.locale()][key];
  }

  setLocale(locale: 'es-CO' | 'en'): void {
    localStorage.setItem('electrostock.locale', locale);
    this.locale.set(locale);
    document.documentElement.lang = locale === 'en' ? 'en' : 'es-CO';
  }
}
